#!/usr/bin/env python3
"""Regenerate type_classes.py from scripts/doc8643.csv (ICAO DOC 8643).

The csv is a local cache that isn't shipped, so the table it produces is
committed and frozen, like categorize.HELICOPTER_TYPES. Jets aren't listed: they
range from a business jet to a U-2, so an engine class says nothing about them.

    python3 scripts/gen_type_classes.py          # rewrite type_classes.py
    python3 scripts/gen_type_classes.py --check  # exit 1 if it would change
"""
import csv
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from categorize import HELICOPTER_TYPES  # noqa: E402

CSV_PATH = ROOT / "scripts" / "doc8643.csv"
OUT_PATH = ROOT / "type_classes.py"
HEADER = '''"""Engine class of each ICAO type designator: generated by
scripts/gen_type_classes.py from ICAO DOC 8643, do not edit by hand.

The collector's record ceilings use it, so a piston homebuilt showing 1,000 kt
or a turboprop showing 120,000 ft can't set an all-time record. Rotorcraft are
in categorize.HELICOPTER_TYPES. Jets, and designators DOC 8643 doesn't have
(balloons, gliders, unknown types), are in neither set and get no class.
"""
'''


def classes(rows):
    piston, turboprop = set(), set()
    for row in rows:
        code = row["type_designator"].strip().upper()
        if not code or code in HELICOPTER_TYPES or row["description"] == "Helicopter":
            continue
        if row["engine_type"] in ("Piston", "Electric"):
            piston.add(code)
        elif row["engine_type"] == "Turboprop/Turboshaft":
            turboprop.add(code)
    return piston, turboprop


def _frozen(name, codes):
    body = textwrap.fill(" ".join(sorted(codes)), width=88, break_on_hyphens=False)
    return f'{name} = frozenset("""\n{body}\n""".split())\n'


def render():
    with open(CSV_PATH, newline="") as f:
        piston, turboprop = classes(csv.DictReader(f))
    return "\n".join([HEADER, _frozen("PISTON_TYPES", piston), _frozen("TURBOPROP_TYPES", turboprop)])


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        same = OUT_PATH.exists() and OUT_PATH.read_text() == text
        print("type_classes.py is up to date" if same else "type_classes.py differs from the csv")
        return 0 if same else 1
    OUT_PATH.write_text(text)
    print(f"wrote {OUT_PATH.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
